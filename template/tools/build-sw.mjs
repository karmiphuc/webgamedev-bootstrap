// Runs after `vite build`. Writes:
//   dist/sw.js        offline service worker; cache name = hash of all file
//                     contents, so ANY change produces a new cache
//   dist/release.json version + commit receipt, used to verify deployments
// Never edit dist/ by hand.

import { createHash } from "node:crypto";
import { execSync } from "node:child_process";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(ROOT, "dist");
const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
const config = JSON.parse(readFileSync(join(ROOT, "game.config.json"), "utf8"));

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });

const files = walk(DIST)
  .map((f) => relative(DIST, f).split(sep).join("/"))
  .filter((f) => f !== "sw.js" && f !== "release.json" && !f.endsWith(".map"))
  .sort();

const hash = createHash("sha256");
for (const f of files) hash.update(f).update(readFileSync(join(DIST, f)));
const contentHash = hash.digest("hex").slice(0, 16);

let commit = "unknown";
try {
  commit = execSync("git rev-parse HEAD", { cwd: ROOT, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
} catch {
  /* not a git checkout */
}

const precache = ["./", ...files.map((f) => `./${f}`)];
const sw = `// Generated by tools/build-sw.mjs. Do not edit.
const CACHE = ${JSON.stringify(`${config.slug}-${contentHash}`)};
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k.startsWith(${JSON.stringify(config.slug + "-")}) && k !== CACHE).map((k) => caches.delete(k))),
    ).then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).catch(() =>
        req.mode === "navigate" ? caches.match("./index.html") : Response.error(),
      );
    }),
  );
});
`;

writeFileSync(join(DIST, "sw.js"), sw);
writeFileSync(
  join(DIST, "release.json"),
  JSON.stringify({ name: config.slug, version: pkg.version, commit, cache: `${config.slug}-${contentHash}`, files: files.length }, null, 2) + "\n",
);
console.log(`sw.js: ${precache.length} files, cache ${config.slug}-${contentHash}`);
